# The karaoke pieces as systemd user services, and everything the panel does with them.
#
#   ohk-asr      Whisper ASR + GPU vocal split + color-wipe builds   (asr_server.py)
#   ohk-app      the karaoke app on this monitor                     (app.py)
#   ohk-app-tv   the app hidden in cage, streamed to the TV browser  (_headless.sh)
#   ohk-tunnel   Cloudflare tunnel to the public hostnames           (cloudflared)
#   ohk-panel    this admin panel
#
# Nothing is ever enabled: no unit starts at login. The panel starts them on demand.
# Background jobs (library maintenance, updates) run as transient units ohk-job-<name>, so
# they survive a panel restart and log to the journal like everything else.
import json
import os
import shlex
import subprocess
import time
import urllib.request

from panel import config as C

UNIT_DIR = os.path.expanduser('~/.config/systemd/user')
APPS_DIR = os.path.expanduser('~/.local/share/applications')

SERVICES = {
	'asr':    {'unit': 'ohk-asr.service', 'label': 'Voice + GPU server'},
	'app':    {'unit': 'ohk-app.service', 'label': 'Karaoke (this monitor)'},
	'app-tv': {'unit': 'ohk-app-tv.service', 'label': 'Karaoke (TV stream)'},
	'tunnel': {'unit': 'ohk-tunnel.service', 'label': 'Public tunnel'},
}
MODE_SERVICES = {
	'monitor': ['asr', 'app'],
	'tv':      ['asr', 'app-tv'],
	'public':  ['asr', 'app-tv', 'tunnel'],
}


def _unit(desc, exec_args, extra_unit = '', extra_service = ''):
	cmd = ' '.join(shlex.quote(a) for a in exec_args)
	return f"""# Generated by the OHK admin panel (panel/services.py). Edits are overwritten.
[Unit]
Description={desc}
{extra_unit}
[Service]
WorkingDirectory={C.REPO}
ExecStart={cmd}
Environment=PYTHONUNBUFFERED=1
TimeoutStopSec=15
{extra_service}
"""


def unit_files():
	run = lambda comp: [C.PY, '-m', 'panel.run', comp]
	after_asr = 'Wants=ohk-asr.service\nAfter=ohk-asr.service\n'
	return {
		'ohk-asr.service': _unit('OHK voice + GPU server (asr_server.py)', run('asr'),
		                         extra_service = 'Restart=on-failure\nRestartSec=5'),
		'ohk-app.service': _unit('OHK karaoke app on this monitor', run('app'),
		                         after_asr + 'Conflicts=ohk-app-tv.service\n',
		                         'Restart=on-failure\nRestartSec=3'),
		'ohk-app-tv.service': _unit('OHK karaoke app streamed to the TV', run('app-tv'),
		                            after_asr + 'Conflicts=ohk-app.service\n',
		                            'Restart=on-failure\nRestartSec=3'),
		'ohk-tunnel.service': _unit('OHK Cloudflare tunnel', run('tunnel'),
		                            'After=ohk-app-tv.service\n',
		                            'Restart=on-failure\nRestartSec=10'),
		'ohk-panel.service': _unit('OHK admin panel', [C.PY, '-m', 'panel.server'],
		                           extra_service = 'Restart=on-failure\nRestartSec=2'),
	}


def desktop_entry():
	return f"""[Desktop Entry]
Type=Application
Name=Karaoke Panel
Comment=Start, stop and check on OpenHomeKaraoke
Exec={shlex.quote(os.path.join(C.REPO, 'scripts', 'ohk-panel'))}
Icon={os.path.join(C.REPO, 'logo.jpg')}
Terminal=false
Categories=AudioVideo;
"""


def install():
	"""Write the unit files + launcher entry if they differ from what's on disk."""
	changed = False
	os.makedirs(UNIT_DIR, exist_ok = True)
	for name, text in unit_files().items():
		path = os.path.join(UNIT_DIR, name)
		try:
			same = open(path).read() == text
		except FileNotFoundError:
			same = False
		if not same:
			with open(path, 'w') as f:
				f.write(text)
			changed = True
	if changed:
		systemctl('daemon-reload')
	os.makedirs(APPS_DIR, exist_ok = True)
	with open(os.path.join(APPS_DIR, 'ohk-panel.desktop'), 'w') as f:
		f.write(desktop_entry())
	return changed


def systemctl(*args, check = False):
	return subprocess.run(['systemctl', '--user', *args], capture_output = True, text = True,
	                      check = check, timeout = 30)


_PROPS = 'Id,ActiveState,SubState,Result,ExecMainStatus,ActiveEnterTimestampMonotonic,NRestarts,LoadState'


def unit_states(units):
	"""State of several units with one systemctl call: {unit: {...}}."""
	r = systemctl('show', *units, '--no-pager', '-p', _PROPS)
	now = time.clock_gettime(time.CLOCK_MONOTONIC)
	out = {}
	for block in r.stdout.strip().split('\n\n'):
		props = dict(L.split('=', 1) for L in block.splitlines() if '=' in L)
		since = int(props.get('ActiveEnterTimestampMonotonic') or 0)
		active = props.get('ActiveState')
		out[props.get('Id')] = {
			'active': active,                        # active|inactive|failed|activating|deactivating
			'sub': props.get('SubState'),
			'result': props.get('Result'),
			'exit_status': props.get('ExecMainStatus'),
			'restarts': int(props.get('NRestarts') or 0),
			'uptime': int(now - since / 1e6) if active == 'active' and since else None,
			'loaded': props.get('LoadState') == 'loaded',
		}
	return {u: out.get(u, {'active': None, 'loaded': False, 'sub': None, 'result': None,
	                       'exit_status': None, 'restarts': 0, 'uptime': None}) for u in units}


def unit_state(unit):
	return unit_states([unit])[unit]


def logs(unit, lines = 80):
	r = subprocess.run(['journalctl', '--user', '-u', unit, '-n', str(lines), '--no-pager',
	                    '-o', 'short-iso'], capture_output = True, text = True, timeout = 15)
	return r.stdout


def last_error(unit):
	"""Most recent error-looking journal line of a unit, for the status card."""
	r = subprocess.run(['journalctl', '--user', '-u', unit, '-n', '200', '--no-pager', '-o', 'cat'],
	                   capture_output = True, text = True, timeout = 15)
	keys = ('error', 'traceback', 'exception', 'refusing', 'failed', 'fatal')
	for line in reversed(r.stdout.splitlines()):
		low = line.lower()
		if any(k in low for k in keys) and 'cosmetic' not in low:
			return line.strip()[:300]
	return None


def http_json(url, timeout = 1.5):
	try:
		with urllib.request.urlopen(url, timeout = timeout) as r:
			body = r.read()
		try:
			return json.loads(body)
		except ValueError:
			return {}
	except Exception:
		return None


def http_ok(url, timeout = 1.5):
	try:
		with urllib.request.urlopen(url, timeout = timeout) as r:
			return 200 <= r.status < 400
	except Exception:
		return False


def legacy_session():
	"""True while start-karaoke.sh's tmux session holds the ports."""
	r = subprocess.run(['tmux', 'has-session', '-t', 'OHK'], capture_output = True)
	return r.returncode == 0


def running_mode():
	st = {k: unit_state(v['unit'])['active'] for k, v in SERVICES.items()}
	up = lambda k: st[k] in ('active', 'activating')
	if up('app-tv'):
		return 'public' if up('tunnel') else 'tv'
	if up('app'):
		return 'monitor'
	return None


def start(mode):
	cfg = C.load()
	if mode not in C.MODES:
		return f'unknown mode {mode}'
	if legacy_session():
		return "start-karaoke.sh is running (tmux session 'OHK'). Stop it first: tmux kill-session -t OHK"
	if mode == 'public':
		if not cfg['admin_password']:
			return 'Public mode needs an admin password: without one, anyone on the internet is admin ' \
			       '(the app\'s /shutdown and /files/delete would be open). Set it in Settings.'
		if not os.path.isfile(os.path.expanduser(cfg['cf_config'])):
			return f"Cloudflare tunnel config not found: {cfg['cf_config']}"
	app_units = [SERVICES[k]['unit'] for k in ('app', 'app-tv')]
	if mode != running_mode() and any(unit_state(u)['active'] in ('active', 'activating') for u in app_units):
		# the app reads mode-dependent flags (public URLs) at start, so switching restarts it
		systemctl('stop', *app_units)
	cfg['mode'] = mode
	C.save(cfg)
	install()
	wanted = [SERVICES[k]['unit'] for k in MODE_SERVICES[mode]]
	if mode != 'public':
		systemctl('stop', '--no-block', SERVICES['tunnel']['unit'])
	for u in wanted:
		systemctl('reset-failed', u)
	r = systemctl('start', '--no-block', *wanted)
	return None if r.returncode == 0 else (r.stderr.strip() or 'systemctl start failed')


def stop():
	units = [SERVICES[k]['unit'] for k in ('tunnel', 'app', 'app-tv', 'asr')]
	r = systemctl('stop', '--no-block', *units)
	return None if r.returncode == 0 else r.stderr.strip()


def restart(key):
	if key not in SERVICES:
		return 'unknown service'
	u = SERVICES[key]['unit']
	systemctl('reset-failed', u)
	r = systemctl('restart', '--no-block', u)
	return None if r.returncode == 0 else r.stderr.strip()


# ---- background jobs --------------------------------------------------------------------
def job_unit(name):
	return f'ohk-job-{name}.service'


def run_job(name, argv, env = None):
	"""Run argv as a transient user unit. RemainAfterExit keeps its result readable."""
	u = job_unit(name)
	st = unit_state(u)
	if st['active'] in ('activating', 'deactivating') or (st['active'] == 'active' and st['sub'] == 'running'):
		return 'already running'
	systemctl('stop', u)
	systemctl('reset-failed', u)
	cmd = ['systemd-run', '--user', '--unit', u, '-p', 'RemainAfterExit=yes',
	       '-p', f'WorkingDirectory={C.REPO}', '-E', 'PYTHONUNBUFFERED=1']
	for k, v in (env or {}).items():
		cmd += ['-E', f'{k}={v}']
	r = subprocess.run(cmd + ['--', *argv], capture_output = True, text = True, timeout = 30)
	return None if r.returncode == 0 else (r.stderr.strip() or 'systemd-run failed')
